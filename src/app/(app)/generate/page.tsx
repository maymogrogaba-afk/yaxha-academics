import Link from "next/link";
import { notFound } from "next/navigation";
import { requireUser } from "@/lib/auth";
import { withUser } from "@/lib/db";
import { env } from "@/lib/env";
import { getSubject, isUuid } from "@/lib/data";
import { aiAvailable } from "@/lib/ai/provider";
import { SUMMARY_MODES } from "@/lib/ai/prompts";
import { Card, Notice, PageHeader } from "@/components/ui";
import { GenerateForm } from "@/components/generate-form";

export const metadata = { title: "Generate Study Pack" };
export const maxDuration = 300;

export default async function GeneratePage({ searchParams }: { searchParams: Promise<{ subject?: string; materials?: string; kind?: string }> }) {
  const user = await requireUser();
  const sp = await searchParams;
  if (!isUuid(sp.subject)) notFound();
  const data = await withUser(user.id, async (tx) => {
    const subject = await getSubject(tx, sp.subject!);
    if (!subject) return null;
    return {
      subject,
      materials: await tx`
        select m.id, m.title, m.kind, m.processing_status, m.processing_error, m.access_status, c.page_count, t.name as topic
        from materials m left join material_contents c on c.material_id = m.id left join topics t on t.id = m.topic_id
        where m.subject_id = ${subject.id} order by (m.processing_status = 'ready') desc, coalesce(m.posted_at, m.created_at) desc limit 300`,
      topics: await tx`select id, name from topics where subject_id = ${subject.id} order by name`,
      summaries: await tx`select id, title as name from summaries where subject_id = ${subject.id} order by updated_at desc limit 50`,
    };
  });
  if (!data) notFound();
  const ai = aiAvailable();
  return (
    <>
      <PageHeader
        eyebrow={<Link href={`/subjects/${data.subject.id}`} className="hover:text-ivory">{data.subject.display_name}</Link>}
        title="Generate Study Pack"
        description="Choose the real course materials to study from. Generated packs cite the pages they come from."
      />
      {!ai && (
        <div className="mb-4">
          <Notice tone="warn" title="AI is not configured yet">
            Summaries, quizzes, and flashcards are generated by an AI model, which needs an API key on the server (AI_API_KEY). Until it is added, you can still read
            materials, make flashcards and notes yourself, and plan your exams. See the README section “Set up AI”.
          </Notice>
        </div>
      )}
      <Card className="p-4 sm:p-6">
        <GenerateForm
          subjectId={data.subject.id}
          materials={data.materials.map((m) => ({
            id: m.id,
            title: m.title,
            kind: m.kind,
            ready: m.processing_status === "ready",
            reason:
              m.access_status === "permission_required"
                ? "No permission to read this file"
                : m.access_status === "not_downloaded"
                  ? "Not downloaded yet — open it to download"
                  : m.processing_error ?? (m.processing_status === "not_applicable" ? "Link or video — no text to read" : "Text not available"),
            pages: m.page_count ?? 0,
            topic: m.topic,
          }))}
          topics={data.topics.map((t) => ({ id: t.id, name: t.name }))}
          summaries={data.summaries.map((s) => ({ id: s.id, name: s.name }))}
          preselected={(sp.materials ?? "").split(",").filter(isUuid)}
          initialKind={sp.kind ?? "summary"}
          modes={Object.entries(SUMMARY_MODES).map(([key, v]) => ({ key, ...v }))}
          aiReady={ai}
          maxSourceChars={env.ai.maxSourceChars}
        />
      </Card>
    </>
  );
}
